"""Notification core: the dedupe decision and the email shape. Pure, testable.

Alert policy (from the plan, tightened for safety):
- First-ever advisory: alert only when the tier is 1+ (nobody needs an alert
  for "good" on day one).
- Escalation (tier rises): alert immediately — safety beats cooldown, same
  principle as the rules engine's immediate-upgrade hysteresis.
- Any other tier change: alert only if the last alert is older than the
  cooldown (12h), so a boundary flap never spams the principal.
"""

ALERT_COOLDOWN_SECONDS = 12 * 3600


def alert_decision(prev_item, new_tier: int, now_ts: int):
    """Decide whether to send. Returns (should_send, reason).

    prev_item: the existing ADVISORY item for the school (dict) or None.
    """
    if prev_item is None:
        return (new_tier >= 1, "first advisory")
    try:
        prev_tier = int(prev_item.get("tier", -1))
    except (TypeError, ValueError):
        prev_tier = -1
    if prev_tier == new_tier:
        return (False, "no tier change")
    if new_tier > prev_tier:
        return (True, "escalation")
    last = int(prev_item.get("alerted_at") or 0)
    if now_ts - last >= ALERT_COOLDOWN_SECONDS:
        return (True, "downgrade, cooldown elapsed")
    return (False, "downgrade within cooldown")


def sns_message(school: dict, advisory_item: dict, dashboard_url: str):
    """The subject/body we publish to SNS. Deterministic given its inputs."""
    band = advisory_item.get("band", "unknown")
    lang = school.get("language", "en")
    text = advisory_item.get("text", {}).get(lang) or advisory_item.get("text", {}).get("en", "")
    subject = f"[SAANS] {school['name']}: air {band} — action for today"
    body = (
        f"{text}\n\n"
        f"— SAANS advisory for {school['name']} (band: {band}, "
        f"generated by {advisory_item.get('source', 'unknown')}).\n"
        f"Live status: {dashboard_url}\n\n"
        "Advisories are modeled estimates, not measurements at the school. "
        "Use your judgment alongside any local reading."
    )
    return subject, body
